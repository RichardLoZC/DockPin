import Foundation
import CoreGraphics

var count = 0
func check(_ name: String, _ condition: @autoclosure () -> Bool) {
    count += 1
    guard condition() else { fputs("FAIL: \(name)\n", stderr); exit(1) }
    print("PASS: \(name)")
}
let main = DisplayInfo(id: 1, uuid: "built-in", name: "Main", bounds: CGRect(x: 0, y: 0, width: 1710, height: 1107), isMain: true)
let left = DisplayInfo(id: 111, uuid: "pad", name: "Pad", bounds: CGRect(x: -1600, y: 0, width: 1600, height: 1068), isMain: false)
let above = DisplayInfo(id: 2, uuid: "above", name: "Above", bounds: CGRect(x: 0, y: -900, width: 1440, height: 900), isMain: false)
let side = DockPolicy(displays: [main, left], preferredUUID: nil)
check("follow system main", side.target?.id == 1)
check("block left display bottom", side.suppresses(CGPoint(x: -800, y: 1067)))
check("four-point boundary", side.suppresses(CGPoint(x: -800, y: 1064)))
check("allow above boundary", !side.suppresses(CGPoint(x: -800, y: 1063.99)))
check("allow main bottom", !side.suppresses(CGPoint(x: 500, y: 1106)))
check("allow normal pointer movement", !side.suppresses(CGPoint(x: -800, y: 400)))
check("Option bypass", !side.suppresses(CGPoint(x: -800, y: 1067), bypass: true))
check("exclusive bottom edge", !side.suppresses(CGPoint(x: -800, y: 1068)))
check("display gap", !side.suppresses(CGPoint(x: -800, y: 1100)))
check("invalid coordinates", !side.suppresses(CGPoint(x: CGFloat.nan, y: 1)))
check("singleton", !DockPolicy(displays: [left], preferredUUID: nil).suppresses(CGPoint(x: -800, y: 1067)))
check("empty catalog", DockPolicy(displays: [], preferredUUID: "pad").target == nil)
let pinned = DockPolicy(displays: [main, left], preferredUUID: "pad")
check("explicit secondary target", pinned.target?.id == left.id)
check("target remains accessible", !pinned.suppresses(CGPoint(x: -800, y: 1067)))
check("block main when secondary is target", pinned.suppresses(CGPoint(x: 500, y: 1106)))
let unplugged = DockPolicy(displays: [main], preferredUUID: "pad")
check("unplug fallback", unplugged.target?.id == main.id && unplugged.usingFallback)
let replugged = DisplayInfo(id: 999, uuid: "pad", name: "Pad", bounds: left.bounds, isMain: false)
let reconnected = DockPolicy(displays: [main, replugged], preferredUUID: "pad")
check("replug uses UUID instead of transient ID", reconnected.target?.id == 999 && !reconnected.usingFallback)
check("side by side exposes bottom", side.summonPoint(for: main) != nil)
let lower = DisplayInfo(id: 3, uuid: "below", name: "Below", bounds: CGRect(x: 0, y: 1107, width: 1710, height: 900), isMain: false)
let stacked = DockPolicy(displays: [main, lower], preferredUUID: nil)
check("fully covered bottom unsupported", stacked.summonPoint(for: main) == nil)
check("lower display bottom supported", stacked.summonPoint(for: lower) != nil)
let offset = DisplayInfo(id: 4, uuid: "offset", name: "Offset", bounds: CGRect(x: 300, y: 1107, width: 1710, height: 900), isMain: false)
let shifted = DockPolicy(displays: [main, offset], preferredUUID: nil)
check("choose exposed part", shifted.summonPoint(for: main) == CGPoint(x: 150, y: 1106))
let topPolicy = DockPolicy(displays: [main, above], preferredUUID: nil)
check("negative y bottom protection", topPolicy.suppresses(CGPoint(x: 500, y: -1)))
check("upper display bottom fully covered", topPolicy.summonPoint(for: above) == nil)
check("modern full-display Dock window", side.display(intersecting: main.bounds)?.id == main.id)
check("older thin Dock bar", side.display(intersecting: CGRect(x: -1000, y: 1000, width: 500, height: 68))?.id == left.id)
check("unknown Dock geometry", side.display(intersecting: CGRect(x: 8000, y: 0, width: 10, height: 20)) == nil)
check("null Dock geometry", side.display(intersecting: .null) == nil)
let changedMain = DisplayInfo(id: left.id, uuid: left.uuid, name: left.name, bounds: left.bounds, isMain: true)
let oldMain = DisplayInfo(id: main.id, uuid: main.uuid, name: main.name, bounds: main.bounds, isMain: false)
check("main follows system role, not array order or focused screen", DockPolicy(displays: [oldMain, changedMain], preferredUUID: nil).target?.id == changedMain.id)
var click = PointerTakeover()
click.observe(ownEvent: false, buttonDown: true, delta: .zero, location: .zero, expected: .zero)
click.observe(ownEvent: false, buttonDown: false, delta: .zero, location: .zero, expected: .zero)
check("quick down+up remains cancelled before next tick", click.interrupted)
var slow = PointerTakeover()
slow.observe(ownEvent: false, buttonDown: false, delta: CGPoint(x: 1, y: 0), location: .zero, expected: .zero)
check("slow one-point movement immediately cancels", slow.interrupted)
var own = PointerTakeover()
own.observe(ownEvent: true, buttonDown: false, delta: CGPoint(x: 0, y: 2), location: CGPoint(x: 100, y: 100), expected: .zero)
check("tagged relocation events do not self-cancel", !own.interrupted)
own.observe(ownEvent: false, buttonDown: false, delta: .zero, location: CGPoint(x: 1, y: 0), expected: .zero)
check("stationary pointer notification tolerates rounding", !own.interrupted)
own.observe(ownEvent: false, buttonDown: false, delta: .zero, location: CGPoint(x: 100, y: 100), expected: .zero)
check("unmarked remote pointer jump cancels", own.interrupted)
var disabled = PointerTakeover(); disabled.interrupt()
check("lost input observer cancels safely", disabled.interrupted)
print("\(count) checks passed")
